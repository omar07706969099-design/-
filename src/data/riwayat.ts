export const getRiwayahById = (id: RiwayahId): RiwayahInfo => {
  return RIWAYAT.find((r) => r.id === id) || RIWAYAT[0];
};

export const getRiwayatBySchool = (schoolId: string): RiwayahInfo[] => {
  if (schoolId === 'madinah') {
    return RIWAYAT.filter((r) => r.id === 'warsh' || r.id === 'qaloon');
  }
  if (schoolId === 'kufa') {
    return RIWAYAT.filter((r) => r.id === 'hafs' || r.id === 'shouba' || r.id === 'khalaf' || r.id === 'duri_kisai');
  }
  if (schoolId === 'basra') {
    return RIWAYAT.filter((r) => r.id === 'doori' || r.id === 'soosi');
  }
  return RIWAYAT;
};

/**
 * Construct audio URL for any reciter (either Ayah-by-Ayah or full Surah file)
 */
export function getAudioUrl(reciter: Reciter, surahNumber: number, ayahNumber: number): string {
  const s = String(surahNumber).padStart(3, '0');
  const a = String(ayahNumber).padStart(3, '0');

  if (reciter.audioType === 'surah') {
    // Direct link to the complete Surah MP3
    const base = reciter.folderOrServer.endsWith('/')
      ? reciter.folderOrServer
      : `${reciter.folderOrServer}/`;
    return `${base}${s}.mp3`;
  }

  // Ayah-by-Ayah audio from EveryAyah CDN
  return `https://everyayah.com/data/${reciter.folderOrServer}/${s}${a}.mp3`;
}

/**
 * Get reciters filtered by Riwayah
 */
export function getRecitersByRiwayah(riwayahId: RiwayahId): Reciter[] {
  return RECITERS.filter((r) => r.riwayahId === riwayahId);
}

/**
 * Get default prominent reciter for a given Riwayah
 */
export function getDefaultReciterForRiwayah(riwayahId: RiwayahId): Reciter {
  const matching = getRecitersByRiwayah(riwayahId);
  return matching[0] || RECITERS[0];
}
